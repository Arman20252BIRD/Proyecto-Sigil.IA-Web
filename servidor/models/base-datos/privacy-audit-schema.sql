CREATE TABLE IF NOT EXISTS privacy_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type TEXT NOT NULL,
    version TEXT NOT NULL,
    title TEXT NOT NULL,
    content_hash TEXT,
    document_url TEXT,
    effective_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (document_type, version)
);

CREATE TABLE IF NOT EXISTS privacy_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
    document_id BIGINT REFERENCES privacy_documents(id) ON DELETE SET NULL,
    consent_type TEXT NOT NULL,
    accepted BOOLEAN NOT NULL,
    version TEXT NOT NULL,
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,
    ip_address INET,
    user_agent TEXT,
    source TEXT NOT NULL DEFAULT 'web',
    CHECK (consent_type IN ('privacy_notice', 'biometric', 'marketing', 'terms'))
);

CREATE INDEX IF NOT EXISTS privacy_consents_admin_idx ON privacy_consents(admin_id, accepted_at DESC);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT REFERENCES admins(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    resource_type TEXT,
    resource_id TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    ip_address INET,
    user_agent TEXT,
    success BOOLEAN NOT NULL DEFAULT TRUE,
    failure_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS audit_logs_admin_created_idx ON audit_logs(admin_id, created_at DESC);
CREATE INDEX IF NOT EXISTS audit_logs_action_created_idx ON audit_logs(action, created_at DESC);

