);

CREATE TABLE IF NOT EXISTS privacy_consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
    document_id BIGINT REFERENCES privacy_documents(id) ON DELETE SET NULL,
    consent_type TEXT NOT NULL,
    accepted BOOLEAN NOT NULL,
    version TEXT NOT NULL,
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,
    ip_address INET,
    user_agent TEXT,
    source TEXT NOT NULL DEFAULT 'web',
    CHECK (consent_type IN ('privacy_notice', 'biometric', 'marketing', 'terms'))
);

CREATE INDEX IF NOT EXISTS privacy_consents_admin_idx ON privacy_consents(admin_id, accepted_at DESC);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
